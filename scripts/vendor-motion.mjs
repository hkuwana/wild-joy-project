import {build} from 'esbuild';
import {mkdir, writeFile} from 'node:fs/promises';
import {gzipSync} from 'node:zlib';
import {readFile} from 'node:fs/promises';
await mkdir('site/vendor',{recursive:true});
await build({stdin:{contents:'export { scroll } from "motion";',resolveDir:process.cwd()},bundle:true,minify:true,format:'iife',globalName:'WildJoyMotion',target:['es2020'],outfile:'site/vendor/motion-scroll.js',banner:{js:'/*! Motion 14.10.1 — MIT. See motion-LICENSE.txt. Generated by scripts/vendor-motion.mjs. */'}});
const notices = await Promise.all(['motion','framer-motion','motion-dom','motion-utils'].map(async name => `${name}\n${await readFile(`node_modules/${name}/LICENSE.md`,'utf8')}`));
await writeFile('site/vendor/motion-LICENSE.txt',notices.join('\n\n'));
const bytes=await readFile('site/vendor/motion-scroll.js');
console.log(`Motion scroll: ${bytes.length} bytes, ${gzipSync(bytes).length} bytes gzip.`);
